const TABLES: Record<Lang, Strings> = { en, ru, zh, es, pt, ja, de, fr, ko }

// Language names as people write them in Claude Code's `language` setting,
// in English or in the language itself.
const NAMES: [Lang, RegExp][] = [
  ['en', /^english/i],
  ['ru', /^(russian|русск|рус)/i],
  ['zh', /^(chinese|mandarin|中文|汉语|漢語|简体|繁體|普通话)/i],
  ['es', /^(spanish|español|espanol|castellano)/i],
  ['pt', /^(portuguese|português|portugues)/i],
  ['ja', /^(japanese|日本)/i],
  ['de', /^(german|deutsch)/i],
  ['fr', /^(french|français|francais)/i],
  ['ko', /^(korean|한국)/i],
]

// Three-letter codes (ISO 639-2) and the common "jp".
const CODES: Record<string, Lang> = {
  eng: 'en', rus: 'ru', zho: 'zh', chi: 'zh', spa: 'es', por: 'pt',
  jpn: 'ja', jp: 'ja', deu: 'de', ger: 'de', fra: 'fr', fre: 'fr', kor: 'ko',
}

/**
 * The table for a language name ("japanese", "Español") or a locale code
 * ("ja", "pt_BR.UTF-8", "zh-CN"); English for any other language, and
 * undefined where the value names none ("", "C", "POSIX"), so the next
 * source is asked.
 */
export const langOf = (value: unknown): Lang | undefined => {
  if (typeof value !== 'string') return undefined
  const v = value.trim()
  if (!v || /^(c|posix)([._@]|$)/i.test(v)) return undefined
  const code = /^([a-z]{2,3})([-_.@]|$)/i.exec(v)?.[1].toLowerCase()
  if (code) return (LANGS as readonly string[]).includes(code) ? (code as Lang) : CODES[code] ?? 'en'
  return NAMES.find(([, re]) => re.test(v))?.[0] ?? 'en'
}

export let t: Strings = en

export async function pickLang($: EngineInterface, option: unknown) {
  let lang = (LANGS as readonly unknown[]).includes(option) ? (option as Lang) : undefined
  lang ??= langOf(await $.settings.read({ key: 'language' }).catch(() => undefined))
  lang ??= langOf(await $.env.get('LC_ALL'))
  lang ??= langOf(await $.env.get('LANG'))
  t = TABLES[lang ?? 'en']
  return lang ?? 'en'
}
